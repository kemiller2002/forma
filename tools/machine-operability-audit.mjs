import fs from "node:fs";
import path from "node:path";
import { loadCatalog } from "./catalog/load.mjs";
import { auditMachineContract } from "./catalog/machine-operability.mjs";

const root = process.cwd();
const args = new Set(process.argv.slice(2));
const write = args.has("--write");
const check = args.has("--check");

const catalog = await loadCatalog(root);
const entries = catalog.components.map(component => ({
  slug: component.slug,
  name: component.name,
  category: component.category,
  behavior: component.behavior,
  ...component.machine,
  metadataProblems: auditMachineContract(component)
})).map(entry => ({
  ...entry,
  status: entry.metadataProblems.length ? "needs-retrofit" : entry.status,
  reasons: entry.metadataProblems.length ? [...entry.reasons, ...entry.metadataProblems] : entry.reasons
}));

const summary = {
  total: entries.length,
  pass: entries.filter(entry => entry.status === "pass").length,
  needsTest: entries.filter(entry => entry.status === "needs-test").length,
  needsRetrofit: entries.filter(entry => entry.status === "needs-retrofit").length
};

const report = {
  contract: "forma-machine-operability",
  contractVersion: "1.0.0",
  summary,
  components: entries
};

const json = JSON.stringify(report, null, 2) + "\n";
const byStatus = status => entries.filter(entry => entry.status === status);
const row = entry => `| \`${entry.slug}\` | ${entry.name} | ${entry.interaction} | ${entry.directManipulation ? "yes" : "no"} | ${entry.reasons.join("; ") || "conforms to derived baseline"} |`;
const section = (title, status) => {
  const items = byStatus(status);
  return [
    `## ${title} (${items.length})`,
    "",
    "| Component | Name | Interaction | Direct manipulation | Finding |",
    "| --- | --- | --- | --- | --- |",
    ...(items.length ? items.map(row) : ["| _None_ | | | | |"]),
    ""
  ].join("\n");
};

const markdown = [
  "# Forma Machine-Operability Retrofit Audit",
  "",
  "This file is generated by `tools/machine-operability-audit.mjs`. It classifies the complete current Forma component catalog against `requirements/MACHINE-OPERABILITY.md`.",
  "",
  `**Total:** ${summary.total}  `,
  `**Pass:** ${summary.pass}  `,
  `**Needs executable parity test:** ${summary.needsTest}  `,
  `**Needs retrofit:** ${summary.needsRetrofit}`,
  "",
  "A `needs-test` component already exposes a semantic path but delegates behavior to the application/Limen layer, so pointer/keyboard/programmatic parity still needs executable evidence. A `needs-retrofit` component has a structural contract problem and should receive a dedicated work item.",
  "",
  section("Needs retrofit", "needs-retrofit"),
  section("Needs executable parity test", "needs-test"),
  section("Pass", "pass")
].join("\n");

const jsonPath = path.join(root, "catalog", "machine-operability.json");
const mdPath = path.join(root, "docs", "MACHINE-OPERABILITY-AUDIT.md");

const compare = (file, expected) => fs.existsSync(file) && fs.readFileSync(file, "utf8") === expected;

if (write) {
  fs.writeFileSync(jsonPath, json);
  fs.writeFileSync(mdPath, markdown + "\n");
}

if (check) {
  const stale = [];
  if (!compare(jsonPath, json)) stale.push(path.relative(root, jsonPath));
  if (!compare(mdPath, markdown + "\n")) stale.push(path.relative(root, mdPath));
  if (stale.length) {
    console.error(`Machine-operability audit is stale: ${stale.join(", ")}. Run npm run machine:audit.`);
    process.exitCode = 1;
  }
}

console.log(JSON.stringify(summary));
