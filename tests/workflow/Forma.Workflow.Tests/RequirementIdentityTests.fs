/// Requirement identity (FMO-019): the component contract for data-requirement-id.
module RequirementIdentityTests

open System
open System.IO
open Harness
open Forma.Workflow

let private el = Markup.el
let private text = Markup.text

/// A Forma field: wrapper, label and the control (the public field pattern).
let private field (id: string) (label: string) (control: Markup) =
    el "div" [ "class", "ef-field" ] [ el "label" [ "class", "ef-field__label"; "for", id ] [ text label ]; control ]

let private statement =
    field "statement" "Problem statement" (el "textarea" [ "id", "statement"; "name", "statement"; "class", "ef-input" ] [])

let private title = field "title" "Title" (el "input" [ "id", "title"; "name", "title"; "type", "text"; "class", "ef-input" ] [])

let private ok (r: Result<Markup, RequirementIdentityError>) =
    match r with
    | Ok m -> m
    | Error e -> fail $"unexpected refusal: {e}"

let private refused (r: Result<Markup, RequirementIdentityError>) =
    match r with
    | Ok m -> fail $"expected a refusal, got {Markup.toCompactHtml m}"
    | Error e -> e

/// The fixture the browser test opens: identified Forma markup rendered by Markup.renderAll.
let fixtureBody () =
    [ el "h1" [] [ text "Requirement identity fixture" ]
      ok (RequirementIdentity.identify TextArea "INV-001" statement)
      ok (RequirementIdentity.identify TextInput "INV-002" title)
      el "button" [ "type", "button"; "class", "ef-button"; RequirementIdentity.Attribute, "INV-004" ] [ text "Start investigation" ]
      el "ul" [] [ for key in [ "H1"; "H2" ] -> el "li" [] [ ok (RequirementIdentity.identifyInstance Button "INV-009" (Some key) (el "button" [ "type", "button"; "class", "ef-button" ] [ text $"Edit hypothesis {key}" ])) ] ]
      el "p" [ "hidden", "" ] [ ok (RequirementIdentity.identify Display "INV-090" (el "span" [] [ text "hidden display" ])) ]
      ok (RequirementIdentity.identify Button "INV-091" (el "button" [ "type", "button"; "class", "ef-button"; "disabled", "" ] [ text "Disabled action" ])) ]

let private fixtureDocument () =
    let head =
        [ "<!doctype html>"
          "<html lang=\"en\">"
          "<head>"
          "  <meta charset=\"utf-8\">"
          "  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
          "  <title>Requirement identity fixture</title>"
          "  <link rel=\"stylesheet\" href=\"/dist/tokens.css\">"
          "  <link rel=\"stylesheet\" href=\"/dist/foundations.css\">"
          "  <link rel=\"stylesheet\" href=\"/dist/components.css\">"
          "</head>"
          "<body>"
          "<!-- Generated by tests/workflow/Forma.Workflow.Tests (RequirementIdentityTests): FORMA_UPDATE_GOLDEN=1 rewrites it. -->"
          "<main>" ]

    String.concat "\n" head + "\n" + Markup.renderAll (fixtureBody ()) + "</main>\n</body>\n</html>\n"

let all =
    [ test "requirement identity goes on the control inside a field wrapper, not on the wrapper or the label" (fun () ->
          let html = Markup.toCompactHtml (ok (RequirementIdentity.identify TextArea "INV-001" statement))
          expect (html.Contains "<textarea id=\"statement\" name=\"statement\" class=\"ef-input\" data-requirement-id=\"INV-001\">") html
          expect (not (html.Contains "<div class=\"ef-field\" data-requirement-id")) "the wrapper must not carry the ID"
          expect (not (html.Contains "<label class=\"ef-field__label\" for=\"statement\" data-requirement-id")) "the label must not carry the ID")
      test "identity leaves every existing attribute, the label association and the role untouched" (fun () ->
          let before = Markup.toCompactHtml title
          let after = Markup.toCompactHtml (ok (RequirementIdentity.identify TextInput "INV-002" title))
          equal before (after.Replace(" data-requirement-id=\"INV-002\"", "")) "only the identity attribute is added")
      test "identity is stable across re-renders" (fun () ->
          let render () = Markup.toHtml (ok (RequirementIdentity.identify TextInput "INV-002" title))
          equal (render ()) (render ()) "two renders")
      test "an ID for a component kind the markup does not contain is refused (no attribute on an unrelated element)" (fun () ->
          match refused (RequirementIdentity.identify TextInput "INV-001" statement) with
          | NoMatchingElement("INV-001", TextInput) -> ()
          | other -> fail $"{other}"
          match refused (RequirementIdentity.identify TextInput "INV-001" (el "div" [ "hidden", "" ] [])) with
          | NoMatchingElement _ -> ()
          | other -> fail $"{other}")
      test "markup with two candidate controls is ambiguous and refused" (fun () ->
          match refused (RequirementIdentity.identify TextInput "INV-002" (el "div" [] [ title; title ])) with
          | AmbiguousElement("INV-002", 2) -> ()
          | other -> fail $"{other}")
      test "an element already identified is not re-identified" (fun () ->
          let once = ok (RequirementIdentity.identify TextInput "INV-002" title)
          match refused (RequirementIdentity.identify TextInput "INV-003" once) with
          | AlreadyIdentified "INV-002" -> ()
          | other -> fail $"{other}")
      test "IDs and instance keys are validated" (fun () ->
          match refused (RequirementIdentity.identify TextInput "" title) with
          | InvalidRequirementId _ -> ()
          | other -> fail $"{other}"
          match refused (RequirementIdentity.identify TextInput "INV 002\"" title) with
          | InvalidRequirementId _ -> ()
          | other -> fail $"{other}"
          match refused (RequirementIdentity.identifyInstance TextInput "INV-002" (Some "") title) with
          | InvalidInstanceKey _ -> ()
          | other -> fail $"{other}")
      test "every supported component accepts only its own element kind" (fun () ->
          let cases =
              [ TextInput, el "input" [ "type", "email" ] [], true
                TextInput, el "input" [ "type", "checkbox" ] [], false
                Checkbox, el "input" [ "type", "checkbox" ] [], true
                Select, el "select" [] [], true
                Button, el "input" [ "type", "submit" ] [], true
                Button, el "div" [ "role", "button" ] [], false
                Link, el "a" [ "href", "#/x" ] [], true
                Link, el "a" [] [], false
                Display, el "dd" [] [], true
                Display, el "input" [] [], false
                Region, el "section" [] [], true ]
          for comp, markup, expected in cases do
              equal expected (RequirementIdentity.accepts comp markup) $"{comp} accepts {Markup.toCompactHtml markup}")
      test "duplicate IDs in one scope are detected; repeated controls with distinct instance keys are not duplicates" (fun () ->
          let a = ok (RequirementIdentity.identify Button "INV-004" (el "button" [] [ text "A" ]))
          let b = ok (RequirementIdentity.identify Button "INV-004" (el "button" [] [ text "B" ]))
          match RequirementIdentity.duplicates [ a; el "div" [] [ b ] ] with
          | [ DuplicateRequirementId("INV-004", 2) ] -> ()
          | other -> fail $"{other}"
          let keyed key = ok (RequirementIdentity.identifyInstance Button "INV-009" (Some key) (el "button" [] [ text key ]))
          equal [] (RequirementIdentity.duplicates [ keyed "H1"; keyed "H2" ]) "distinct keys"
          equal 1 (RequirementIdentity.duplicates [ keyed "H1"; keyed "H1" ]).Length "shared key")
      test "bindings list every identity in document order" (fun () ->
          let bound = RequirementIdentity.bindings (fixtureBody ())
          equal [ "INV-001"; "INV-002"; "INV-004"; "INV-009"; "INV-009"; "INV-090"; "INV-091" ] (bound |> List.map (fun (id, _, _) -> id)) "order"
          equal [] (RequirementIdentity.duplicates (fixtureBody ())) "the fixture has no duplicate")
      test "the browser fixture is exactly the rendered identified markup" (fun () ->
          let file = path [ "tests"; "browser"; "fixture"; "requirement-identity.html" ]
          if Environment.GetEnvironmentVariable "FORMA_UPDATE_GOLDEN" = "1" then File.WriteAllText(file, fixtureDocument ())
          expect (File.Exists file) "tests/browser/fixture/requirement-identity.html is missing (run with FORMA_UPDATE_GOLDEN=1)"
          equal (fixtureDocument ()) (File.ReadAllText file) "fixture") ]
